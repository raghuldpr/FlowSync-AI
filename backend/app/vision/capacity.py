"""How many vehicles fit in each approach's camera ROI.

   python -m app.vision.capacity                                   # print
   python -m app.vision.capacity --write config/topology.physical.yaml   # copy of topology.yaml with per-approach capacities

The simulation default (8 per link) is far larger than a real tabletop lane holds. For the physical table (or the
synthetic camera), run the backend with  FLOWSYNC_TOPOLOGY_PATH=config/topology.physical.yaml.
The written copy is generated (yaml comments are not preserved): edit topology.yaml and regenerate.
"""
import argparse
import sys

import yaml

from ..config import Settings
from ..core.topology import Topology
from .config import VisionConfig
from .geometry import roi_capacity


def main(argv=None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--write")
    a = p.parse_args(argv)
    s = Settings()
    topo = Topology.load(s.topology_path)
    cfg = VisionConfig.from_topology(topo)
    caps = {aid: roi_capacity(topo, cfg, aid) for aid in topo.approaches}
    print(f"# car {cfg.car_length}x{cfg.car_width} + gap {cfg.car_gap} layout units")
    for aid, c in caps.items():
        print(f"{aid}: capacity {c}  (topology.yaml currently {topo.approaches[aid].capacity})")
    if a.write:
        raw = yaml.safe_load(open(s.topology_path, encoding="utf-8"))
        for aid, c in caps.items():
            raw["approaches"][aid]["capacity"] = c
        with open(a.write, "w", encoding="utf-8", newline="\n") as f:
            f.write("# GENERATED by `python -m app.vision.capacity --write` from topology.yaml (physical-table capacities).\n")
            f.write("# Do not edit: change topology.yaml and regenerate.\n")
            yaml.safe_dump(raw, f, sort_keys=False)
        print("wrote", a.write)
    return 0


if __name__ == "__main__":
    sys.exit(main())
