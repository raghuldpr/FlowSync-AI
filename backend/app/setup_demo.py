"""Generate private demo credentials: account passwords and per-device keys.

    python -m app.setup_demo            # writes .env entries and data/secrets/devices.demo.yaml
    python -m app.setup_demo --force    # replace the FLOWSYNC_* entries of an earlier run

Everything is written ONLY to git-ignored files (`.env`, `data/`). Passwords and keys are never printed: open `.env` to read
them (the operator login is FLOWSYNC_OPERATOR_PASSWORD). Other lines of an existing `.env` (the LLM settings, for example) are
kept. The backend picks the values up through `app.config.Settings` (`.env` is read at import; real environment variables win),
and the generated devices file through FLOWSYNC_DEVICES_PATH. Development defaults still work when no `.env` exists.
"""
import argparse
import secrets
import sys
from pathlib import Path

import yaml

from app.config import ROOT, load_yaml

MANAGED = ("FLOWSYNC_VIEWER_PASSWORD", "FLOWSYNC_OPERATOR_PASSWORD", "FLOWSYNC_ADMIN_PASSWORD", "FLOWSYNC_DEVICES_PATH")
DEVICES_OUT = ROOT / "data" / "secrets" / "devices.demo.yaml"


def new_secret(nbytes: int = 18) -> str:
    return secrets.token_urlsafe(nbytes)


def _keys_of(lines: list) -> set:
    return {ln.split("=", 1)[0].strip() for ln in lines if ln.strip() and not ln.strip().startswith("#") and "=" in ln}


def write_env(env_path: Path, values: dict, force: bool) -> None:
    """Append the managed entries to `.env`, keeping every other line. Refuses to replace existing ones without force."""
    lines = env_path.read_text(encoding="utf-8").splitlines() if env_path.exists() else []
    present = _keys_of(lines) & set(MANAGED)
    if present and not force:
        raise FileExistsError(f"{env_path.name} already sets {', '.join(sorted(present))}; use --force to replace them")
    kept = [ln for ln in lines if ln.split("=", 1)[0].strip() not in MANAGED]
    kept += [f"{k}={v}" for k, v in values.items()]
    env_path.write_text("\n".join(kept) + "\n", encoding="utf-8")


def write_devices(src: Path, out: Path, force: bool) -> int:
    """Copy the device list with a fresh random key for every device. Returns how many keys were generated."""
    if out.exists() and not force:
        raise FileExistsError(f"{out} already exists; use --force to replace it")
    spec = load_yaml(str(src))
    for d in spec["devices"].values():
        d["key"] = new_secret(24)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("# GENERATED by python -m app.setup_demo - private, git-ignored. Do not commit or paste.\n"
                   + yaml.safe_dump(spec, sort_keys=False), encoding="utf-8")
    return len(spec["devices"])


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--force", action="store_true", help="replace the entries and the devices file of an earlier run")
    ap.add_argument("--env", default=str(ROOT / ".env"), help="env file to update (default: .env in the repository root)")
    ap.add_argument("--devices-src", default=str(ROOT / "config" / "devices.yaml"))
    ap.add_argument("--devices-out", default=str(DEVICES_OUT))
    a = ap.parse_args(argv)
    env, out = Path(a.env), Path(a.devices_out)
    # check both targets before writing either, so a refusal leaves everything untouched
    clash = [str(p) for p, existing in ((env, _keys_of(env.read_text(encoding="utf-8").splitlines()) & set(MANAGED) if env.exists() else set()),
                                        (out, out.exists())) if existing]
    if clash and not a.force:
        print(f"Refusing to overwrite: {', '.join(clash)}. Run again with --force to replace them.", file=sys.stderr)
        return 2
    n = write_devices(Path(a.devices_src), out, a.force)
    write_env(env, {"FLOWSYNC_VIEWER_PASSWORD": new_secret(), "FLOWSYNC_OPERATOR_PASSWORD": new_secret(),
                    "FLOWSYNC_ADMIN_PASSWORD": new_secret(), "FLOWSYNC_DEVICES_PATH": str(out)}, a.force)
    print(f"Wrote 3 account passwords to {env} and {n} device keys to {out}. Neither is printed: open {env.name} to read the operator login.")
    print("Restart the backend to use them. Firmware that talks to the backend needs its key from the devices file.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
