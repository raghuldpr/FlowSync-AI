"""Live 'what is built and what is simulated' table, derived from what the data paths actually report.

The hackathon brief requires the demo to state this clearly. Instead of a hand-written slide that can go stale,
each data path labels itself (controller `origin`, traffic `source`, EV position `source`) and this table is built
from those labels, so it is correct whichever mix of hardware and simulation is running.
"""
FRESH_S = 10.0


def _row(component, status, detail):
    return {"component": component, "status": status, "detail": detail}


def build(ctx) -> list:
    now = ctx.store.clock()
    n_int = len(ctx.topology.intersections)
    ctrl = f"Intersection controller ({n_int} intersections, {n_int * 6} lamps)"

    def seen(key):
        v = ctx.prov.get(key)
        return (v[0], now - v[1]) if v else (None, None)

    rows = []
    origin, age = seen("controller")
    if origin is None or age > FRESH_S:
        rows.append(_row(ctrl, "Not connected", "no recent state reports"))
    elif origin == "hardware":
        rows.append(_row(ctrl, "Built", "ESP32 + 74HCT595 LED chain; lamps shown are what the device reports"))
    else:
        rows.append(_row(ctrl, "Simulated", "virtual tabletop runs the same signal state machine as the firmware"))

    src, age = seen("traffic")
    if src is None or age > FRESH_S:
        rows.append(_row("Queue counts", "Not connected", "no recent traffic readings"))
    else:
        label = {"overhead_camera": ("Built", "overhead phone camera + vision pipeline (background differencing in lane ROIs)"),
                 "recorded_video": ("Replay", "recorded video through the real vision pipeline"),
                 "ultrasonic": ("Built", "ultrasonic stop-line sensors"),
                 "simulated": ("Simulated", "counts generated by the simulator / synthetic camera")}[src]
        rows.append(_row("Queue counts", *label))

    src, age = seen("ev_position")
    if src is None or age > FRESH_S:
        rows.append(_row("Emergency vehicle position", "Idle", "no emergency vehicle is being tracked right now"))
    elif src == "camera":
        rows.append(_row("Emergency vehicle position", "Built", "ArUco marker on the toy car, tracked by the overhead camera"))
    else:
        rows.append(_row("Emergency vehicle position", "Simulated", "position generated by the simulator"))

    n_users = len(ctx.roadusers.users)
    rows.append(_row("Road-user alerts (phones)", "Built" if n_users else "Idle",
                     f"{n_users} active session(s): relevance is decided on the server; each user sees only their own feed"
                     if n_users else "no road users connected; open /driver.html on a phone to join"))
    if n_users:
        rows.append(_row("Road-user positions", "Simulated", "each user drives a virtual car along their route (dead-reckoned); phones do not report GPS"))

    llm = ctx.llm.status()
    if getattr(ctx.llm, "forced_down", False):
        rows.append(_row("LLM reasoning layer", "Built", "provider DOWN (drill): deterministic fallback active"))
    elif llm["enabled"]:
        rows.append(_row("LLM reasoning layer", "Built", f"live model {llm['model']}; non-authoritative, proposals need operator confirmation"))
    else:
        rows.append(_row("LLM reasoning layer", "Built", "implemented; no model configured, so answers come from the deterministic fallback"))

    for comp, detail in [
        ("Adaptive signal controller + safety validator", "deterministic pressure-based control; spillback and gridlock rules; every command validated"),
        ("Incident detection, impact assessment, operator alerts", "congestion and stalled-vehicle detection; impact and alternatives computed from the road graph"),
        ("Routing + emergency-vehicle warning lifecycle", "Dijkstra with hysteresis; warnings update / redirect / cancel; fixed lawful wording"),
        ("Roles, audit log, public redaction", "operator login, every restricted action and denial logged; public sees redacted data only"),
    ]:
        rows.append(_row(comp, "Built", detail))
    rows.append(_row("City-scale network", "Simulated" if n_int > 3 else "Idle",
                     f"{n_int}-intersection generated grid: the same controller code, simulated traffic" if n_int > 3
                     else "run the backend on config/topology.grid.yaml for the 12-intersection city view"))
    open_h = ctx.hazards.list("active")
    rows.append(_row("Road conditions (hazards)", "Built",
                     f"{len(open_h)} active; only operator-verified hazards affect routes; the camera pothole finder (a pretrained road-damage model when installed, otherwise a heuristic) only proposes; an operator must verify"))
    return rows
