"""Generate firmware/intersection/lib/flowsync_core/timing_defaults.h from config/topology.yaml.

The tabletop timings live in ONE place (topology.yaml); the firmware copy is generated, and a test fails
if the checked-in header drifts.   python firmware/tools/gen_timing.py
"""
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "firmware" / "intersection" / "lib" / "flowsync_core" / "timing_defaults.h"
FIELDS = ["min_green_ms", "yellow_ms", "all_red_ms", "max_green_ms", "max_red_ms",
          "fallback_green_ms", "command_valid_ms", "backend_lost_ms"]


def render() -> str:
    t = yaml.safe_load((ROOT / "config" / "topology.yaml").read_text(encoding="utf-8"))["timing"]
    vals = ", ".join(f"{t[f]}u" for f in FIELDS)
    return ("// GENERATED by firmware/tools/gen_timing.py from config/topology.yaml. Do not edit.\n"
            "#pragma once\n#include \"signal_fsm.h\"\n\nnamespace fsync {\n"
            f"// order: {', '.join(FIELDS)}\n"
            f"constexpr Timing kTiming = {{{vals}}};\n"
            "}  // namespace fsync\n")


if __name__ == "__main__":
    OUT.write_text(render(), encoding="utf-8", newline="\n")
    print("wrote", OUT)
